"""The reference half of the docs, written by reading the models.

``reference_documents()`` returns ``{name: markdown}`` for every generated
file under ``docs/reference/``; ``llm-browser docs --write`` puts them there
and ``tests/test_docs.py`` fails when what ships no longer matches. Nothing
here is hand-edited, so a field's meaning is maintained once, on the field.
"""

import inspect
import re
import types
import typing
from enum import Enum
from pathlib import Path

from pydantic import BaseModel
from pydantic.fields import FieldInfo

from llm_browser import constants
from llm_browser.behavior import Behavior
from llm_browser.introspect import own_fields, session_methods, step_arms
from llm_browser.models import (
    TEXT_STATES,
    WAIT_STATES,
    BaseStep,
    MatchFields,
    SelectorStep,
    FlowError,
    FlowSuccess,
    MatchWarning,
    RetryHint,
    SkippedStep,
)
from llm_browser.parse import ExtractField
from llm_browser.selectors import (
    CssSelector,
    FallbackSelector,
    IdSelector,
    RefSelector,
    ScopedSelector,
    XpathSelector,
)
from llm_browser.session import BrowserSession

HEADER = (
    "<!-- Generated by `llm-browser docs --write`; edit the models, "
    "not this file. -->\n"
)

# A default longer than this says nothing a reader can use in a table cell.
DEFAULT_MAX_CHARS = 40


def docs_dir() -> Path:
    return Path(__file__).parent / "docs"


# --- Rendering a model ---


def render_type(annotation: object) -> str:
    """A field's type as a flow author would say it, not as pydantic holds it."""
    if annotation is None or annotation is type(None):
        return "None"
    if isinstance(annotation, typing.TypeAliasType):
        return annotation.__name__
    metadata_of = getattr(annotation, "__metadata__", None)
    if metadata_of is not None:
        return render_type(typing.get_args(annotation)[0])
    origin = typing.get_origin(annotation)
    if origin is typing.Literal:
        return " | ".join(f'"{arg}"' for arg in typing.get_args(annotation))
    if origin in (types.UnionType, typing.Union):
        return " | ".join(unique(render_type(a) for a in typing.get_args(annotation)))
    if origin is not None:
        args = ", ".join(render_type(a) for a in typing.get_args(annotation))
        name = getattr(origin, "__name__", str(origin))
        return f"{name}[{args}]" if args else name
    return getattr(annotation, "__name__", str(annotation))


def unique(values: typing.Iterable[str]) -> list[str]:
    return list(dict.fromkeys(values))


def render_value(value: object) -> str:
    if isinstance(value, Enum):
        return repr(value.value)
    if isinstance(value, BaseModel):
        return repr(value)
    return repr(value)


def render_default(field: FieldInfo) -> str:
    if field.is_required():
        return "required"
    value = field.default_factory() if field.default_factory else field.default  # type: ignore[call-arg]
    text = render_value(value)
    return text if len(text) <= DEFAULT_MAX_CHARS else "—"


def field_rows(model: type[BaseModel], names: typing.Iterable[str]) -> list[list[str]]:
    rows = []
    for name in names:
        field = model.model_fields[name]
        alias = field.alias or name
        rows.append(
            [
                f"`{alias}`",
                f"`{render_type(field.annotation)}`",
                f"`{render_default(field)}`",
                field.description or "",
            ]
        )
    return rows


def table(headings: list[str], rows: list[list[str]]) -> str:
    """A pipe inside a cell would end it, so every cell is escaped once here."""
    divider = " | ".join("---" for _ in headings)
    body = "".join(
        f"| {' | '.join(cell.replace('|', chr(92) + '|') for cell in row)} |\n"
        for row in rows
    )
    return f"| {' | '.join(headings)} |\n| {divider} |\n{body}"


def field_table(model: type[BaseModel], names: typing.Iterable[str]) -> str:
    rows = field_rows(model, names)
    if not any(row[-1] for row in rows):
        rows = [row[:-1] for row in rows]
        return table(["field", "type", "default"], rows)
    return table(["field", "type", "default", "meaning"], rows)


# Docstrings are written in reST for the editor; the docs are markdown.
RST_ROLE = re.compile(r":(?:class|func|meth|attr|mod|data|exc):`~?([^`]+)`")


def docstring(obj: object) -> str:
    text = inspect.getdoc(obj) or ""
    text = RST_ROLE.sub(lambda m: f"`{m.group(1).rsplit('.', 1)[-1]}`", text)
    return text.replace("``", "`")


def model_section(
    title: str, model: type[BaseModel], names: list[str] | None = None
) -> str:
    fields = model.model_fields if names is None else names
    parts = [f"## {title}", docstring(model)]
    if fields:
        parts.append(field_table(model, fields))
    return "\n\n".join(part for part in parts if part) + "\n"


# --- The documents ---


# Written once under "Targeting" rather than in all fifteen step sections.
SHARED_TARGET_FIELDS = set(MatchFields.model_fields) | {"selector"}


def local_fields(step_class: type[BaseStep]) -> list[str]:
    """A step's own rows: the targeting fields are documented once, unless the
    step redeclares one to mean something different."""
    declared = getattr(step_class, "__annotations__", {})
    return [
        name
        for name in own_fields(step_class)
        if name not in SHARED_TARGET_FIELDS or name in declared
    ]


def targeting_section() -> str:
    names = ["selector", *MatchFields.model_fields]
    return (
        "## Targeting\n\n"
        "Every step that acts on an element takes these; a step that "
        "redeclares one says so in its own table.\n\n"
        + field_table(SelectorStep, names)
    )


def steps_document() -> str:
    sections = [
        model_section(f"`{action}`", step_class, local_fields(step_class))
        for action, step_class in step_arms()
    ]
    return (
        "# Steps\n\n"
        "One section per `action:` a flow can write. Every step also takes the "
        "targeting fields and the shared options at the end.\n\n"
        + "\n".join(sections)
        + "\n"
        + targeting_section()
        + "\n"
        + model_section("Shared options", BaseStep)
    )


def selectors_document() -> str:
    forms = (
        CssSelector,
        XpathSelector,
        IdSelector,
        RefSelector,
        FallbackSelector,
        ScopedSelector,
    )
    intro = (
        "How a step names the element it acts on. A bare string is a CSS "
        "selector; the forms below are the explicit spellings.\n"
    )
    return (
        "# Selectors\n\n"
        + intro
        + "\n"
        + "\n".join(model_section(f"`{form.__name__}`", form) for form in forms)
    )


def waits_document() -> str:
    rows = [
        [f"`{state}`", meaning, "yes" if state in TEXT_STATES else "no"]
        for state, meaning in WAIT_STATES.items()
    ]
    return (
        "# Wait states\n\n"
        "What `wait_for` (and any step's own wait) can wait for. The last "
        "column says whether a `text:` wait accepts the state — text is read "
        "off `innerText`, so only presence and absence mean anything.\n\n"
        + table(["state", "element is", "valid for `text:`"], rows)
    )


def behavior_document() -> str:
    presets = [
        ("human", Behavior.human()),
        ("pace", Behavior.pace()),
        ("off", Behavior.off()),
    ]
    rows = [
        [f"`{name}`", field.description or ""]
        + [f"`{render_value(getattr(preset, name))}`" for _, preset in presets]
        for name, field in Behavior.model_fields.items()
    ]
    return (
        "# Behavior\n\n"
        + docstring(Behavior)
        + "\n\nA run picks a preset by name; a flow that needs one knob "
        "different sets it and the run reports `custom`.\n\n"
        + table(
            ["knob", "meaning", *[f"`{name}`" for name, _ in presets]],
            rows,
        )
    )


def results_document() -> str:
    models = (FlowSuccess, FlowError, RetryHint, SkippedStep, MatchWarning)
    return "# Flow results\n\n" + "\n".join(
        model_section(f"`{model.__name__}`", model) for model in models
    )


def extract_document() -> str:
    return "\n".join(
        [
            "# Extract specs\n",
            "What a `read` step's `extract:` writes, one entry per column.\n",
            "## The compact form\n",
            docstring(ExtractField.parse) + "\n",
            "## The mapping form\n",
            docstring(ExtractField) + "\n",
            "## Readable properties\n",
            "Every name below is read as a JavaScript property; anything else "
            f"is an HTML attribute. The default is `{constants.DEFAULT_EXTRACT_ATTRIBUTE}`, "
            f"under the field name `{constants.DEFAULT_EXTRACT_FIELD}` when the spec "
            "names no fields.\n",
            "\n".join(f"- `{name}`" for name in constants.EXTRACT_PROPERTIES) + "\n",
            "A `read` step's `exclude:` only changes the properties a "
            "descendant is part of: "
            + ", ".join(f"`{name}`" for name in constants.EXCLUDABLE_PROPERTIES)
            + ".\n",
        ]
    )


def signature_of(name: str) -> str:
    try:
        rendered = str(inspect.signature(getattr(BrowserSession, name)))
    except (TypeError, ValueError):
        return name
    return f"{name}{rendered.replace('self, ', '').replace('self', '')}"


def session_document() -> str:
    sections = [
        f"## `{signature_of(name)}`\n\n{docstring(getattr(BrowserSession, name))}\n"
        for name in session_methods()
    ]
    return (
        "# BrowserSession\n\n"
        "The Python surface every flow step is built on; an embedding caller "
        "drives the same methods directly.\n\n" + "\n".join(sections)
    )


DOCUMENTS = {
    "reference/steps": steps_document,
    "reference/selectors": selectors_document,
    "reference/waits": waits_document,
    "reference/behavior": behavior_document,
    "reference/results": results_document,
    "reference/extract": extract_document,
    "reference/session": session_document,
}


def reference_documents() -> dict[str, str]:
    """Every generated document, keyed by its doc name."""
    return {name: HEADER + "\n" + build() for name, build in DOCUMENTS.items()}


def write_reference() -> list[str]:
    """Write every document into the package; answer the paths that changed."""
    changed = []
    for name, text in reference_documents().items():
        path = docs_dir() / f"{name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(name)
    return changed


def stale_reference() -> list[str]:
    """Documents whose shipped text no longer matches the models."""
    return [
        name
        for name, text in reference_documents().items()
        if not (docs_dir() / f"{name}.md").exists()
        or (docs_dir() / f"{name}.md").read_text() != text
    ]
